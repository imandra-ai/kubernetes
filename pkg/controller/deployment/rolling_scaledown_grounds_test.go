// The vectors are region tests generated by ImandraX from an IML model of the
// scale-down arithmetic in rolling.go; expected values come from the model.
const groundsConformanceDir = "../../../.grounds/conformance"

type groundsVectorFile struct {
	Function string `json:"function"`
	Vectors  []struct {
		ID       string           `json:"id"`
		Input    map[string]int32 `json:"input"`
		Expected struct {
			Tuple []json.RawMessage `json:"$tuple"`
		} `json:"expected"`
	} `json:"vectors"`
}

func loadGroundsVectors(t *testing.T, name string) groundsVectorFile {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(groundsConformanceDir, name))
	if err != nil {
		t.Fatalf("reading vectors %s: %v", name, err)
	}
	var f groundsVectorFile
	if err := json.Unmarshal(data, &f); err != nil {
		t.Fatalf("decoding vectors %s: %v", name, err)
	}
	if len(f.Vectors) == 0 {
		t.Fatalf("vectors %s: no vectors", name)
	}
	return f
}

func decodeGrounds(t *testing.T, raw json.RawMessage, into interface{}) {
	t.Helper()
	if err := json.Unmarshal(raw, into); err != nil {
		t.Fatalf("decoding expected value %s: %v", raw, err)
	}
}

// groundsDeployment builds a deployment whose MaxUnavailable resolves to mu
// before clamping. maxSurge is 1 because ResolveFenceposts turns (0, 0) into
// maxUnavailable 1; surge plays no part in the scale-down arithmetic.
func groundsDeployment(d, mu int32) *apps.Deployment {
	maxSurge := intstr.FromInt32(1)
	maxUnavailable := intstr.FromInt32(mu)
	return newDeployment("foo", d, nil, &maxSurge, &maxUnavailable, map[string]string{"foo": "bar"})
}

// Old ReplicaSets get increasing creation timestamps so the controller's sort
// keeps the order the model assumes.
func groundsRS(name string, replicas, available int32, age int) *apps.ReplicaSet {
	base := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	r := rs(name, replicas, map[string]string{"foo": name}, metav1.NewTime(base.Add(time.Duration(age)*time.Minute)))
	r.Status.AvailableReplicas = available
	return r
}

func groundsController(rss ...*apps.ReplicaSet) (*DeploymentController, *fake.Clientset) {
	objs := make([]runtime.Object, 0, len(rss))
	for _, r := range rss {
		objs = append(objs, r.DeepCopy())
	}
	client := fake.NewClientset(objs...)
	return &DeploymentController{client: client, eventRecorder: &record.FakeRecorder{}}, client
}

// storedReplicas reads spec.replicas back from the fake API: on an error path
// the controller returns nil, but earlier updates have already been written.
func storedReplicas(t *testing.T, client *fake.Clientset, rss ...*apps.ReplicaSet) []int32 {
	t.Helper()
	out := make([]int32, 0, len(rss))
	for _, r := range rss {
		got, err := client.AppsV1().ReplicaSets(r.Namespace).Get(t.Context(), r.Name, metav1.GetOptions{})
		if err != nil {
			t.Fatalf("reading back ReplicaSet %s: %v", r.Name, err)
		}
		out = append(out, *got.Spec.Replicas)
	}
	return out
}

func equalInt32s(a, b []int32) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func TestGroundsScaleDownConformance(t *testing.T) {
	t.Run("reconcileOldReplicaSets", func(t *testing.T) {
		f := loadGroundsVectors(t, "reconcile_one.vectors.json")
		for _, v := range f.Vectors {
			t.Run(v.ID, func(t *testing.T) {
				in := v.Input
				var wantScaled bool
				var wantReplicas int32
				decodeGrounds(t, v.Expected.Tuple[0], &wantScaled)
				decodeGrounds(t, v.Expected.Tuple[1], &wantReplicas)

				deployment := groundsDeployment(in["d"], in["mu"])
				newRS := groundsRS("foo-new", in["nr"], in["na"], 10)
				oldRS := groundsRS("foo-old-1", in["r"], in["a"], 1)
				dc, client := groundsController(oldRS, newRS)
				_, ctx := ktesting.NewTestContext(t)

				scaled, err := dc.reconcileOldReplicaSets(ctx, []*apps.ReplicaSet{oldRS, newRS}, []*apps.ReplicaSet{oldRS}, newRS, deployment)
				if err != nil {
					t.Fatalf("input %v: unexpected error: %v", in, err)
				}
				got := storedReplicas(t, client, oldRS)
				if scaled != wantScaled || got[0] != wantReplicas {
					t.Errorf("input %v: model (scaled=%v, old=%d), code (scaled=%v, old=%d)", in, wantScaled, wantReplicas, scaled, got[0])
				}
			})
		}
	})

	t.Run("cleanupUnhealthyReplicas", func(t *testing.T) {
		f := loadGroundsVectors(t, "cleanup2u.vectors.json")
		for _, v := range f.Vectors {
			t.Run(v.ID, func(t *testing.T) {
				in := v.Input
				var wantCount int32
				var wantErr bool
				var wantReplicas []int32
				decodeGrounds(t, v.Expected.Tuple[0], &wantCount)
				decodeGrounds(t, v.Expected.Tuple[1], &wantErr)
				decodeGrounds(t, v.Expected.Tuple[2], &wantReplicas)

				deployment := groundsDeployment(10, 2)
				old1 := groundsRS("foo-old-1", in["r1"], in["a1"], 1)
				old2 := groundsRS("foo-old-2", in["r2"], in["a2"], 2)
				dc, client := groundsController(old1, old2)
				_, ctx := ktesting.NewTestContext(t)

				_, count, err := dc.cleanupUnhealthyReplicas(ctx, []*apps.ReplicaSet{old1, old2}, deployment, in["m"])
				got := storedReplicas(t, client, old1, old2)
				if count != wantCount || (err != nil) != wantErr || !equalInt32s(got, wantReplicas) {
					t.Errorf("input %v: model (count=%d, err=%v, old=%v), code (count=%d, err=%v, old=%v)", in, wantCount, wantErr, wantReplicas, count, err, got)
				}
			})
		}
	})

	t.Run("scaleDownOldReplicaSetsForRollingUpdate", func(t *testing.T) {
		f := loadGroundsVectors(t, "scale_down2u.vectors.json")
		for _, v := range f.Vectors {
			t.Run(v.ID, func(t *testing.T) {
				in := v.Input
				var wantCount int32
				var wantReplicas []int32
				decodeGrounds(t, v.Expected.Tuple[0], &wantCount)
				decodeGrounds(t, v.Expected.Tuple[1], &wantReplicas)

				deployment := groundsDeployment(in["d"], in["mu"])
				newRS := groundsRS("foo-new", in["nr"], in["na"], 10)
				old1 := groundsRS("foo-old-1", in["r1"], in["a1"], 1)
				old2 := groundsRS("foo-old-2", in["r2"], in["a2"], 2)
				dc, client := groundsController(old1, old2, newRS)
				_, ctx := ktesting.NewTestContext(t)

				count, err := dc.scaleDownOldReplicaSetsForRollingUpdate(ctx, []*apps.ReplicaSet{old1, old2, newRS}, []*apps.ReplicaSet{old1, old2}, deployment)
				if err != nil {
					t.Fatalf("input %v: unexpected error: %v", in, err)
				}
				got := storedReplicas(t, client, old1, old2)
				if count != wantCount || !equalInt32s(got, wantReplicas) {
					t.Errorf("input %v: model (count=%d, old=%v), code (count=%d, old=%v)", in, wantCount, wantReplicas, count, got)
				}
			})
		}
	})
}
