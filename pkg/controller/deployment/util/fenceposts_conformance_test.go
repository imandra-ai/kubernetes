// fencepostVectorsFile holds test vectors generated by ImandraX from an IML
// model of ResolveFenceposts (see .grounds/conformance at the repository root).
var fencepostVectorsFile = filepath.Join("..", "..", "..", "..", ".grounds", "conformance", "deployment_fenceposts.vectors.json")

type fencepostVariant struct {
	C    string            `json:"$c"`
	Args []json.RawMessage `json:"args"`
}

type fencepostVector struct {
	ID    string `json:"id"`
	Input struct {
		MaxSurge       fencepostVariant `json:"max_surge"`
		MaxUnavailable fencepostVariant `json:"max_unavailable"`
		Desired        int32            `json:"desired"`
	} `json:"input"`
	Expected struct {
		Tuple [2]int32 `json:"$tuple"`
	} `json:"expected"`
}

// toIntOrString maps the model's `ios option` (None | Some (Int n) | Some (Pct p))
// to the *IntOrString ResolveFenceposts takes.
func toIntOrString(v fencepostVariant) (*intstr.IntOrString, error) {
	switch v.C {
	case "None":
		return nil, nil
	case "Some":
		if len(v.Args) != 1 {
			return nil, fmt.Errorf("Some takes 1 argument, got %d", len(v.Args))
		}
		var inner fencepostVariant
		if err := json.Unmarshal(v.Args[0], &inner); err != nil {
			return nil, err
		}
		if len(inner.Args) != 1 {
			return nil, fmt.Errorf("%s takes 1 argument, got %d", inner.C, len(inner.Args))
		}
		var n int32
		if err := json.Unmarshal(inner.Args[0], &n); err != nil {
			return nil, err
		}
		switch inner.C {
		case "Int":
			r := intstr.FromInt32(n)
			return &r, nil
		case "Pct":
			r := intstr.FromString(fmt.Sprintf("%d%%", n))
			return &r, nil
		}
		return nil, fmt.Errorf("unknown constructor %q", inner.C)
	}
	return nil, fmt.Errorf("unknown constructor %q", v.C)
}

func TestResolveFencepostsConformance(t *testing.T) {
	data, err := os.ReadFile(fencepostVectorsFile)
	if err != nil {
		t.Fatalf("reading vectors: %v", err)
	}
	var file struct {
		Vectors []fencepostVector `json:"vectors"`
	}
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatalf("decoding vectors: %v", err)
	}
	if len(file.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	for _, v := range file.Vectors {
		t.Run(v.ID, func(t *testing.T) {
			maxSurge, err := toIntOrString(v.Input.MaxSurge)
			if err != nil {
				t.Fatalf("max_surge: %v", err)
			}
			maxUnavailable, err := toIntOrString(v.Input.MaxUnavailable)
			if err != nil {
				t.Fatalf("max_unavailable: %v", err)
			}
			surge, unavailable, err := ResolveFenceposts(maxSurge, maxUnavailable, v.Input.Desired)
			if err != nil {
				t.Fatalf("ResolveFenceposts(%v, %v, %d) returned error: %v", maxSurge, maxUnavailable, v.Input.Desired, err)
			}
			if got := [2]int32{surge, unavailable}; got != v.Expected.Tuple {
				t.Errorf("ResolveFenceposts(%v, %v, %d) = %v, model expects %v", maxSurge, maxUnavailable, v.Input.Desired, got, v.Expected.Tuple)
			}
		})
	}
}
